const CHAINS = ["Здоровье+", "Аптека Мир", "Фарм-Лайн", "Ласка", "СитиФарма"];
const DISTRICTS = {
  "Центральный": [55.7558, 37.6173],
  "Северный": [55.8304, 37.5200],
  "Южный": [55.6500, 37.6200],
  "Восточный": [55.7800, 37.7800],
  "Западный": [55.7300, 37.4400],
};
const STREETS = ["Ленина", "Мира", "Советская", "Гагарина", "Садовая", "Пушкина", "Победы", "Новая", "Школьная", "Речная", "Луговая", "Парковая"];

const medicines = M.map((m, i) => ({
  id: `med-${String(i + 1).padStart(3, "0")}`,
  name: m[0], activeSubstance: m[1], dosage: m[2], form: m[3],
  manufacturer: m[4], country: m[5], category: m[6],
  description: m[8], indications: m[9], contraindications: m[10],
  imageUrl: `/img/med-${String(i + 1).padStart(3, "0")}.svg`,
  _base: m[7],
}));

const palette = ["#0d9488", "#2563eb", "#9333ea", "#db2777", "#ea580c", "#16a34a", "#0891b2", "#ca8a04"];
medicines.forEach((m, i) => {
  const c = palette[i % palette.length];
  const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
  writeFileSync(new URL(`${m.id}.svg`, img), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 240" role="img" aria-label="${esc(m.name)}">
<rect width="240" height="240" fill="#f1f5f9"/>
<rect x="55" y="35" width="130" height="170" rx="10" fill="#fff" stroke="#cbd5e1" stroke-width="2"/>
<rect x="55" y="35" width="130" height="50" rx="10" fill="${c}"/>
<rect x="55" y="70" width="130" height="15" fill="${c}"/>
<path d="M115 45h10v8h8v10h-8v8h-10v-8h-8V53h8z" fill="#fff"/>
<text x="120" y="120" text-anchor="middle" font-family="sans-serif" font-size="${m.name.length > 12 ? 14 : 18}" font-weight="700" fill="#0f172a">${esc(m.name)}</text>
<text x="120" y="142" text-anchor="middle" font-family="sans-serif" font-size="12" fill="#475569">${esc(m.dosage)}</text>
<text x="120" y="188" text-anchor="middle" font-family="sans-serif" font-size="11" fill="${c}">${esc(m.form)}</text>
</svg>\n`);
});

const pharmacies = [];
let pn = 0;
for (const [district, [lat, lng]] of Object.entries(DISTRICTS)) {
  for (let k = 0; k < 4; k++) {
    pn++;
    const chain = CHAINS[(pn + k) % CHAINS.length];
    const is24 = rnd() < 0.2;
    const open = pick([7, 8, 9]);
    const close = pick([20, 21, 22]);
    pharmacies.push({
      id: `ph-${String(pn).padStart(3, "0")}`,
      name: `${chain} №${pn * 3 + 1}`,
      chain,
      address: `ул. ${pick(STREETS)}, ${Math.floor(rnd() * 80) + 1}`,
      district,
      coordinates: { lat: +(lat + (rnd() - 0.5) * 0.06).toFixed(5), lng: +(lng + (rnd() - 0.5) * 0.09).toFixed(5) },
      workingHours: is24 ? "Круглосуточно" : `${String(open).padStart(2, "0")}:00–${close}:00`,
      is24Hours: is24,
      rating: +(3.4 + rnd() * 1.6).toFixed(1),
      hasDelivery: rnd() < 0.6,
    });
  }
}

const offers = [];
const now = Date.now();
for (const m of medicines) {
  const n = 7 + Math.floor(rnd() * 9);
  const shuffled = [...pharmacies].sort(() => rnd() - 0.5).slice(0, n);
  for (const p of shuffled) {
    const r = rnd();
    offers.push({
      medicineId: m.id,
      pharmacyId: p.id,
      price: Math.round(m._base * (0.85 + rnd() * 0.4)),
      availability: r < 0.65 ? "in_stock" : r < 0.88 ? "on_order" : "out_of_stock",
      updatedAt: new Date(now - Math.floor(rnd() * 72) * 3600_000).toISOString(),
    });
  }
}
medicines.forEach((m) => delete m._base);

const w = (name, data) => writeFileSync(new URL(name, out), JSON.stringify(data, null, 1) + "\n");
w("medicines.json", medicines);
w("pharmacies.json", pharmacies);
w("offers.json", offers);
